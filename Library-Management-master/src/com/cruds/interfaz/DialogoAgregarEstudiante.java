    private void btnAgregarEstudianteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarEstudianteActionPerformed
        codigo = txtCodigo.getText().trim();
        String nombre = txtNombre.getText().trim();
        
        if(nombre.length() == 0 || codigo.length() == 0)
        {
            JOptionPane.showMessageDialog(rootPane, "Por favor ingrese el nombre y el código", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        LibroDAO libroDAO = new LibroDAO();

        if (libroDAO.existeEstudiante(new Estudiante(codigo, nombre))) {
            JOptionPane.showMessageDialog(rootPane, "El estudiante ya existe", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        } else {
            libroDAO.agregarEstudiante(new Estudiante(codigo, nombre));
            JOptionPane.showMessageDialog(rootPane, "Estudiante agregado correctamente", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
        }
    }//GEN-LAST:event_btnAgregarEstudianteActionPerformed

